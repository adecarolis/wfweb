#!/bin/sh
# What this build calls itself.
#
#   tools/build-id.sh               full version: 0.9.5 or 0.9.5+dev.e49e8c76
#   tools/build-id.sh --id          the build id alone, empty for a release
#   tools/build-id.sh --header F    write F (wfweb_build.h), only when its
#                                   content changes, so make rebuilds nothing
#                                   when the commit has not moved
#
# A build is a release when HEAD is the commit tagged v<WFWEB_VERSION>, and a
# development build otherwise: <version>+dev.<short sha>. Without git (a
# source tarball) there is nothing to tell them apart and the bare version
# stands.
#
# WFWEB_BUILD_ID in the environment overrides the detection: "release", or an
# id such as dev.20261115.e49e8c76. CI sets it so that the binary, the page
# footer and the package file name carry one string (build.yml's meta job),
# and because a container or a Docker context may have no usable git.
#
# The Windows build has no shell: buildid.pri does the same in qmake.

set -e

ROOT=$(cd "$(dirname "$0")/.." && pwd -P)

VERSION=$(sed -n 's/^#define WFWEB_VERSION "\(.*\)".*/\1/p' "$ROOT/include/wfweb_version.h")
if [ -z "$VERSION" ]; then
    echo "build-id.sh: could not read WFWEB_VERSION from $ROOT/include/wfweb_version.h" >&2
    exit 1
fi

# Only this checkout's own git: a tarball unpacked inside some other
# repository must not pick up that repository's commit.
SHA=
if [ "$(git -C "$ROOT" rev-parse --show-toplevel 2>/dev/null)" = "$ROOT" ]; then
    SHA=$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || true)
fi

if [ -n "${WFWEB_BUILD_ID:-}" ]; then
    if [ "$WFWEB_BUILD_ID" = release ]; then ID=; else ID=$WFWEB_BUILD_ID; fi
elif [ -z "$SHA" ]; then
    ID=
elif git -C "$ROOT" tag --points-at HEAD 2>/dev/null | grep -qx "v$VERSION"; then
    ID=
else
    ID="dev.$SHA"
fi

# The commit for the --version banner. CI ids end in it.
if [ -z "$SHA" ] && [ -n "$ID" ]; then
    SHA=${ID##*.}
fi

case "${1:-}" in
    "")
        echo "$VERSION${ID:++$ID}"
        ;;
    --id)
        echo "$ID"
        ;;
    --header)
        OUT=${2:?build-id.sh --header needs a file name}
        TMP="$OUT.tmp.$$"
        {
            echo "// Generated by tools/build-id.sh on every build. Do not edit, do not commit."
            echo "#define WFWEB_BUILD_ID \"$ID\""
            echo "#define WFWEB_BUILD_GIT \"$SHA\""
        } > "$TMP"
        if cmp -s "$TMP" "$OUT"; then rm -f "$TMP"; else mv -f "$TMP" "$OUT"; fi
        ;;
    *)
        echo "usage: build-id.sh [--id | --header <file>]" >&2
        exit 2
        ;;
esac
